/* Measure how loud every engine is with every ping, and write firmware/src/engine_levels.h: the gains that make
 * them all as loud as each other.   cc -O2 -Ifirmware/src -o build/measure tools/measure_levels.c && build/measure */
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <math.h>
#define FS 44100u
#define HALF_FRAMES 256u
#define BOARD_SMK37 0
#define TRACKS 4u
static void fm1_irq_off(void) {}
static void fm1_irq_on(void) {}
#define ENGINE_LEVEL_TABLE
#define ENGINES_MAX 4
#define PINGS_MAX 15
static uint16_t engine_levels[ENGINES_MAX][PINGS_MAX], engine_dark[ENGINES_MAX][PINGS_MAX];
#include "engine.h"

static uint8_t g_pos = 40;
static double note_rms(uint8_t engine, uint8_t ping, uint8_t bright, uint8_t note)
{
    memset(pluck_voices, 0, sizeof pluck_voices);
    pluck_part_t *s = &pluck_parts[0];
    memset(s, 0, sizeof *s);
    s->engine = engine; s->ping = ping;
    s->macro[PLUCK_BRIGHTNESS] = bright; s->macro[PLUCK_POSITION] = g_pos;
    s->adsr = (pluck_adsr_t){0, 0, 300, 100};      /* no envelope: the engine's own sound */
    pluck_lfo_rate(&s->lfo, 10);
    pluck_set_level(s, PLUCK_MAX_LEVEL);
    pluck_start(0, 0, note, 100, PLUCK_GAIN_ONE);
    int32_t out[2 * HALF_FRAMES];
    /* the loudest 46 ms (eight blocks) of the first half second: how loud the note feels, for a long tone and a
     * short hit alike */
    double window[8] = {0}, loudest = 0;
    for (uint32_t block = 0; block < FS / 2 / HALF_FRAMES; block++) {
        memset(out, 0, sizeof out);
        pluck_mix(out, HALF_FRAMES);
        double sum = 0;
        for (uint32_t i = 0; i < HALF_FRAMES; i++) sum += (double)out[2 * i] * out[2 * i];
        window[block % 8] = sum;
        double w = 0;
        for (uint32_t i = 0; i < 8; i++) w += window[i];
        if (w > loudest) loudest = w;
    }
    return sqrt(loudest / (8 * HALF_FRAMES));
}

/* the average loudness in dB over notes, positions and a few throws of the noise */
static double average(uint8_t e, uint8_t p, uint8_t bright)
{
    static const uint8_t notes[] = {48, 60, 72}, positions[] = {10, 40, 80, 120};
    double l = 0;
    for (uint32_t n = 0; n < 3; n++)
        for (uint32_t q = 0; q < 4; q++)
            for (uint32_t r = 0; r < (p <= PING_BROWN ? 3u : 1u); r++) {
                g_pos = positions[q];
                l += 20 * log10(note_rms(e, p, bright, notes[n]) + 1) / (p <= PING_BROWN ? 3 : 1);
            }
    return l / 12;
}

int main(int argc, char **argv)
{
    double level[ENGINES][PING_COUNT], dark[ENGINES][PING_COUNT], target = 0;
    uint32_t count = 0;
    for (uint32_t e = 0; e < ENGINES; e++)
        for (uint32_t p = 0; p < PING_COUNT; p++) engine_levels[e][p] = engine_dark[e][p] = 4096;
    for (uint32_t e = 0; e < ENGINES; e++)            /* 1: each engine and ping, at middle brightnesses */
        for (uint32_t p = 0; p <= engine_last_ping((uint8_t)e); p++) {
            level[e][p] = (average((uint8_t)e, (uint8_t)p, 60) + average((uint8_t)e, (uint8_t)p, 110)) / 2;
            target += level[e][p];
            count++;
        }
    target /= count;                                  /* everything to the average loudness */
    for (uint32_t e = 0; e < ENGINES; e++)
        for (uint32_t p = 0; p <= engine_last_ping((uint8_t)e); p++) {
            double g = pow(10, (target - level[e][p]) / 20);
            engine_levels[e][p] = (uint16_t)lround((g > 15.9 ? 15.9 : g) * 4096);
        }
    for (uint32_t e = 0; e < ENGINES; e++)            /* 2: the darkest brightness, with those gains */
        for (uint32_t p = 0; p <= engine_last_ping((uint8_t)e); p++) {
            double d = pow(10, (target - average((uint8_t)e, (uint8_t)p, 0)) / 20);
            d = d > 8 ? 8 : d < 0.25 ? 0.25 : d;
            engine_dark[e][p] = (uint16_t)lround(d * 4096);
            dark[e][p] = d;
        }
    FILE *f = argc > 1 ? fopen(argv[1], "w") : stdout;
    fprintf(f, "/* Generated by tools/measure_levels.c. engine_levels: the gain of each engine (row) with each ping\n"
               " * (column), 4096 = x1. engine_dark: the extra gain at brightness 0, reached gradually below 32. */\n");
    for (int t = 0; t < 2; t++) {
        fprintf(f, "static const uint16_t %s[ENGINES][PING_COUNT] = {\n", t ? "engine_dark" : "engine_levels");
        for (uint32_t e = 0; e < ENGINES; e++) {
            fprintf(f, "    {");
            for (uint32_t p = 0; p < PING_COUNT; p++)
                fprintf(f, "%s%u", p ? ", " : "", t ? engine_dark[e][p] : engine_levels[e][p]);
            fprintf(f, "},   /* %s */\n", engine_names[e]);
        }
        fprintf(f, "};\n");
    }
    for (uint32_t e = 0; e < ENGINES; e++)
        for (uint32_t p = 0; p <= engine_last_ping((uint8_t)e); p++)
            fprintf(stderr, "%-6s %-12s %5.1f dB  gain %5.2f  dark %5.2f\n", engine_names[e], ping_names[p],
                    level[e][p], engine_levels[e][p] / 4096.0, dark[e][p]);
    return 0;
}
